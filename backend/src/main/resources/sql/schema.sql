CREATE TABLE IF NOT EXISTS investment (
                                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          ticker VARCHAR(20) NOT NULL,
                                          name VARCHAR(200) NOT NULL,
                                          provider VARCHAR(100) NOT NULL,
                                          exchange VARCHAR(20) NOT NULL,
                                          provider_symbol VARCHAR(50) NOT NULL UNIQUE,
                                          trading_currency CHAR(3) NOT NULL,
                                          inception_date DATE,
                                          ongoing_charge_percent NUMERIC(7, 4),
                                          region VARCHAR(50),

                                          CONSTRAINT uq_investment_exchange_ticker
                                              UNIQUE (exchange, ticker)
);

CREATE TABLE IF NOT EXISTS historical_price (
                                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                investment_id BIGINT NOT NULL,
                                                price_date DATE NOT NULL,
                                                open_price NUMERIC(18, 6) NOT NULL,
                                                high_price NUMERIC(18, 6) NOT NULL,
                                                low_price NUMERIC(18, 6) NOT NULL,
                                                close_price NUMERIC(18, 6) NOT NULL,
                                                adjusted_close NUMERIC(18, 6) NOT NULL,
                                                volume BIGINT NOT NULL,
                                                dividend_amount NUMERIC(18, 6) NOT NULL,

                                                CONSTRAINT fk_historical_price_investment
                                                    FOREIGN KEY (investment_id)
                                                        REFERENCES investment(id)
                                                        ON DELETE CASCADE,

                                                CONSTRAINT uq_historical_price_investment_date
                                                    UNIQUE (investment_id, price_date)
);